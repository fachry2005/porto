export default function usePortfolio() {
  const [projects, setProjects] = useState<any[]>([])
  const [certificates, setCertificates] =
    useState<any[]>([])
  const [techStacks, setTechStacks] =
    useState<any[]>([])

  const [loading, setLoading] = useState(true)

  useEffect(() => {
    loadPortfolio()
  }, [])

  const loadPortfolio = async () => {
    const cachedProjects =
      sessionStorage.getItem(
        'portfolioProjects'
      )

    const cachedCertificates =
      sessionStorage.getItem(
        'portfolioCertificates'
      )

    const cachedTechStacks =
      sessionStorage.getItem(
        'portfolioTechStacks'
      )

    if (cachedProjects) {
      try {
        const parsed = JSON.parse(cachedProjects)
        const hasLocal = parsed.some((p: any) => p.id === 'kopi-nusantara')
        setProjects(hasLocal ? parsed : [...localProjectsData, ...parsed])
      } catch {
        setProjects(localProjectsData)
      }
    } else {
      setProjects(localProjectsData)
    }

    if (cachedCertificates) {
      try {
        const parsed = JSON.parse(cachedCertificates)
        const hasMyskill = parsed.some((c: any) => c.id === 'myskill-lovable-ai-cert')
        setCertificates(hasMyskill ? parsed : [...localCertificatesData, ...parsed.filter((c: any) => c.id !== 'devnet-local-cert')])
      } catch {
        setCertificates(localCertificatesData)
      }
    }

    if (cachedTechStacks) {
      setTechStacks(
        JSON.parse(cachedTechStacks)
      )
    }

    const [
      projectsData,
      certificatesData,
      techStacksData,
    ] = await Promise.all([
      fetchProjects(),
      fetchCertificates(),
      fetchTechStacks(),
    ])

    const allCertificates = [...localCertificatesData, ...(certificatesData || [])]
    const allProjects = [...localProjectsData, ...(projectsData || [])]

    setProjects(allProjects)
    setCertificates(allCertificates)
    setTechStacks(techStacksData || [])

    sessionStorage.setItem(
      'portfolioProjects',
      JSON.stringify(allProjects)
    )

    sessionStorage.setItem(
      'portfolioCertificates',
      JSON.stringify(allCertificates)
    )

    sessionStorage.setItem(
      'portfolioTechStacks',
      JSON.stringify(techStacksData || [])
    )

    setLoading(false)
  }

  return {
    projects,
    certificates,
    techStacks,
    loading,
  }
}
