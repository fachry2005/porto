export default function usePortfolio() {
  const [projects, setProjects] = useState<any[]>([])
  const [certificates, setCertificates] =
    useState<any[]>([])
  const [techStacks, setTechStacks] =
    useState<any[]>([])

  const [loading, setLoading] = useState(true)

  useEffect(() => {
    loadPortfolio()
  }, [])

  const loadPortfolio = async () => {
    const cachedProjects =
      sessionStorage.getItem(
        'portfolioProjects'
      )

    const cachedCertificates =
      sessionStorage.getItem(
        'portfolioCertificates'
      )

    const cachedTechStacks =
      sessionStorage.getItem(
        'portfolioTechStacks'
      )

    if (cachedProjects) {
      try {
        const parsed = JSON.parse(cachedProjects)
        const hasLocal = parsed.some((p: any) => p.id === 'kopi-nusantara')
        setProjects(hasLocal ? parsed : [...localProjectsData, ...parsed])
      } catch {
        setProjects(localProjectsData)
      }
    } else {
      setProjects(localProjectsData)
    }

    if (cachedCertificates) {
      try {
        const parsed = JSON.parse(cachedCertificates)
        const localIds = new Set(localCertificatesData.map((l: any) => l.id))
        setCertificates([...localCertificatesData, ...parsed.filter((c: any) => !localIds.has(c.id))])
      } catch {
        setCertificates(localCertificatesData)
      }
    } else {
      setCertificates(localCertificatesData)
    }

    if (cachedTechStacks) {
      try {
        const parsed = JSON.parse(cachedTechStacks)
        const localIds = new Set(localTechStacksData.map((l: any) => l.id))
        setTechStacks([...localTechStacksData, ...parsed.filter((t: any) => !localIds.has(t.id))])
      } catch {
        setTechStacks(localTechStacksData)
      }
    } else {
      setTechStacks(localTechStacksData)
    }

    const [
      projectsData,
      certificatesData,
      techStacksData,
    ] = await Promise.all([
      fetchProjects(),
      fetchCertificates(),
      fetchTechStacks(),
    ])

    const allCertificates = [...localCertificatesData, ...(certificatesData || [])]
    const allProjects = [...localProjectsData, ...(projectsData || [])]
    const localTechIds = new Set(localTechStacksData.map((l: any) => l.id))
    const allTechStacks = [
      ...localTechStacksData,
      ...(techStacksData || []).filter((t: any) => !localTechIds.has(t.id)),
    ]

    setProjects(allProjects)
    setCertificates(allCertificates)
    setTechStacks(allTechStacks)

    sessionStorage.setItem(
      'portfolioProjects',
      JSON.stringify(allProjects)
    )

    sessionStorage.setItem(
      'portfolioCertificates',
      JSON.stringify(allCertificates)
    )

    sessionStorage.setItem(
      'portfolioTechStacks',
      JSON.stringify(allTechStacks)
    )

    setLoading(false)
  }

  return {
    projects,
    certificates,
    techStacks,
    loading,
  }
}
